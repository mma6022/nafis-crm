def table_is_autoincrement(create_sql: str | None) -> bool:
    if not create_sql:
        return False
    return "AUTOINCREMENT" in create_sql.upper()


def list_tables(scon: sqlite3.Connection) -> list[str]:
    rows = scon.execute(
        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
    ).fetchall()
    return [r[0] for r in rows]


def pragma_cols(scon: sqlite3.Connection, table: str):
    return list(scon.execute(f"PRAGMA table_info({qid(table)})"))


def pragma_fks(scon: sqlite3.Connection, table: str):
    return list(scon.execute(f"PRAGMA foreign_key_list({qid(table)})"))


def pragma_indexes(scon: sqlite3.Connection, table: str):
    return list(scon.execute(f"PRAGMA index_list({qid(table)})"))


def build_create_table(scon: sqlite3.Connection, table: str, create_sql: str | None) -> str:
    cols = pragma_cols(scon, table)
    auto = table_is_autoincrement(create_sql)
    pk_cols = [c[1] for c in cols if c[5]]
    col_sql = []
    for cid, name, ctype, notnull, dflt, pk in cols:
        typ = sqlite_type_to_pg(ctype, bool(pk) and len(pk_cols) == 1 and (ctype or "").upper() in ("INTEGER", "INT", ""), auto)
        typ = refine_numeric_type(scon, table, name, typ)
        bits = [qid(name), typ]
        if notnull and not (pk and typ.endswith("IDENTITY")):
            bits.append("NOT NULL")
        if dflt is not None and "IDENTITY" not in typ:
            d = rewrite_sqlite_fns_in_default(str(dflt))
            bits.append("DEFAULT " + d)
        col_sql.append(" ".join(bits))
    checks, uniques = extract_table_extras(create_sql)
    # Column-level CHECKs are not table-constraint clauses; pick them up too.
    checks = extract_all_checks(create_sql)
    extras = []
    if len(pk_cols) > 1:
        extras.append("PRIMARY KEY (" + ", ".join(qid(c) for c in pk_cols) + ")")
    elif len(pk_cols) == 1:
        # Already declared on the column if integer; if text PK, add it.
        pkcol = next(c for c in cols if c[5] and c[1] == pk_cols[0])
        if (pkcol[2] or "").upper() not in ("INTEGER", "INT", ""):
            extras.append("PRIMARY KEY (" + qid(pk_cols[0]) + ")")
        elif (pkcol[2] or "").upper() == "" and not typ_is_identity(col_sql, pk_cols[0]):
            extras.append("PRIMARY KEY (" + qid(pk_cols[0]) + ")")
    already_uq: set[tuple[str, ...]] = set()
    for u in uniques:
        # PRIMARY KEY is already emitted from pragma table_info; skip the SQL copy.
        if re.search(r"\bPRIMARY\s+KEY\b", u, re.I) and "FOREIGN" not in u.upper():
            continue
        extras.append(rewrite_glob_in_sql(u))
        cols_u = unique_clause_cols(u)
        if cols_u:
            already_uq.add(cols_u)
    # Column-level UNIQUE (idempotency_key TEXT UNIQUE, etc.) from PRAGMA origin=u
    for ucols in sqlite_unique_colsets(scon, table, pk_cols):
        key = tuple(ucols)
        if key in already_uq:
            continue
        extras.append("UNIQUE (" + ", ".join(qid(c) for c in ucols) + ")")
        already_uq.add(key)
    for ch in checks:
        extras.append(ch)
    body = ",\n  ".join(col_sql + extras)
    return f"CREATE TABLE {qid(table)} (\n  {body}\n)"



def refine_numeric_type(scon: sqlite3.Connection, table: str, col: str, pg_type: str) -> str:
    """Widen INTEGER->REAL/TEXT when SQLite actually stored non-integers (typeless)."""
    if not pg_type.startswith("BIGINT"):
        return pg_type
    try:
        kinds = {r[0] for r in scon.execute(
            f"SELECT DISTINCT typeof({qid(col)}) FROM {qid(table)}"
        ) if r[0] and r[0] != "null"}
    except Exception:
        return pg_type
    if "text" in kinds or "blob" in kinds:
        # Keep identity PKs as BIGINT; typeless text in a non-pk int column becomes TEXT.
        if "IDENTITY" in pg_type:
            return pg_type
        return pg_type.replace("BIGINT", "TEXT", 1)
    if "real" in kinds:
        if "IDENTITY" in pg_type:
            return pg_type  # PK identity stays integer; unexpected
        return pg_type.replace("BIGINT", "DOUBLE PRECISION", 1)
    return pg_type


def typ_is_identity(col_sql: list[str], colname: str) -> bool:
    return any(qid(colname) in s and "IDENTITY" in s for s in col_sql)


def row_canonical(row: tuple[Any, ...]) -> bytes:
    parts: list[bytes] = []
    for v in row:
        if v is None:
            parts.append(b"N")
        elif isinstance(v, bool):
            # shouldn't appear; treat as int
            parts.append(b"I" + str(int(v)).encode())
        elif isinstance(v, int):
            parts.append(b"I" + str(v).encode())
        elif isinstance(v, float):
            if v.is_integer() and abs(v) <= 2**63-1:
                parts.append(b"I" + str(int(v)).encode())
            else:
                parts.append(b"F" + repr(v).encode())
        elif isinstance(v, (bytes, memoryview, bytearray)):
            parts.append(b"B" + bytes(v).hex().encode())
        else:
            parts.append(b"S" + str(v).encode("utf-8", "surrogatepass"))
        parts.append(b"|")
    return b"".join(parts)


def checksum_sqlite(scon: sqlite3.Connection, table: str, cols: list[str]) -> tuple[int, str]:
    order = ", ".join(qid(c) for c in cols)
    select = ", ".join(qid(c) for c in cols)
    n = 0
    h = hashlib.sha256()
    cur = scon.execute(f"SELECT {select} FROM {qid(table)} ORDER BY {order}")
    while True:
        chunk = cur.fetchmany(2000)
        if not chunk:
            break
        for row in chunk:
            n += 1
            h.update(row_canonical(row))
            h.update(b"\n")
    return n, h.hexdigest()


def checksum_pg(pcon, table: str, cols: list[str]) -> tuple[int, str]:
    order = ", ".join(qid(c) for c in cols)
    select = ", ".join(qid(c) for c in cols)
    n = 0
    h = hashlib.sha256()
    with pcon.cursor() as cur:
        cur.execute(f"SELECT {select} FROM {qid(table)} ORDER BY {order}")
        while True:
            chunk = cur.fetchmany(2000)
            if not chunk:
                break
            for row in chunk:
                n += 1
                h.update(row_canonical(row))
                h.update(b"\n")
    return n, h.hexdigest()


def reset_sequences(pcon, scon: sqlite3.Connection, tables: list[str]) -> None:
    with pcon.cursor() as cur:
        for table in tables:
            cols = pragma_cols(scon, table)
            int_pks = [c[1] for c in cols if c[5] and (c[2] or "").upper() in ("INTEGER", "INT", "")]
            if len(int_pks) != 1:
                continue
            pk = int_pks[0]
            cur.execute(
                """
                SELECT pg_get_serial_sequence(%s, %s)
                """,
                (table, pk),
            )
            seq = cur.fetchone()[0]
            if not seq:
                continue
            cur.execute(f"SELECT COALESCE(MAX({qid(pk)}), 0) FROM {qid(table)}")
            mx = cur.fetchone()[0] or 0
            # setval is_called=true so next nextval is mx+1; if empty, is_called=false
            if mx <= 0:
                cur.execute("SELECT setval(%s, 1, false)", (seq,))
            else:
                cur.execute("SELECT setval(%s, %s, true)", (seq, int(mx)))


def convert_index_sql(sql: str) -> str | None:
    if not sql:
        return None
    if re.search(r"\bjulianday\s*\(\s*created_at\s*\)", sql, re.I) and "idx_call_logs_customer_actual_time" in sql:
        return JULIANDAY_INDEX_SQL or re.sub(
            r"\bjulianday\s*\(", "sqlite_julianday_immutable(", sql, flags=re.I
        )
    s = rewrite_glob_in_sql(sql)
    s = re.sub(r"\bIFNULL\s*\(", "COALESCE(", s, flags=re.I)
    s = re.sub(r"\bjulianday\s*\(", "sqlite_julianday_immutable(", s, flags=re.I)
    # SQLite: CREATE [UNIQUE] INDEX [IF NOT EXISTS] name ON tbl (exprs)
    # already valid in PG for most cases, including julianday(...) once the fn exists.
    s = re.sub(r"\bIF\s+NOT\s+EXISTS\b", "", s, flags=re.I)
    return s


def convert_view_sql(sql: str) -> str:
    return rewrite_glob_in_sql(sql)


# ---- trigger translation (best-effort) ----
RAISE_SELECT = re.compile(
    r"SELECT\s+RAISE\s*\(\s*ABORT\s*,\s*('(?:[^']|'')*')\s*\)\s*(?:WHERE\s+(.*?))?;",
    re.I | re.S,
)
RAISE_CASE = re.compile(
    r"SELECT\s+CASE\s+WHEN\s+(.*?)\s+THEN\s+RAISE\s*\(\s*ABORT\s*,\s*('(?:[^']|'')*')\s*\)\s+END\s*;",
    re.I | re.S,
)


def sqlite_trigger_to_pg(name: str, sql: str) -> tuple[str, str] | None:
    """Return (function_sql, trigger_sql) or None if we cannot translate."""
    if _new_sqlite_trigger_to_pg is not None:
        try:
            fn_sql, trg_sql, _meta = _new_sqlite_trigger_to_pg(name, sql)
            return fn_sql, trg_sql
        except Exception:
            return None
    if not sql:
        return None
    m = re.search(
        r"CREATE\s+TRIGGER\s+(?:\"([^\"]+)\"|(\S+))\s+(BEFORE|AFTER|INSTEAD\s+OF)\s+(INSERT|UPDATE|DELETE)"
        r"(?:\s+OF\s+([^\s]+(?:\s*,\s*[^\s]+)*))?\s+ON\s+(?:\"([^\"]+)\"|(\S+))"
        r"(?:\s+WHEN\s+(.*?))?\s+BEGIN\s+(.*)\s+END\s*;?\s*$",
        sql.strip(),
        re.I | re.S,
    )
    if not m:
        return None
    tname = m.group(1) or m.group(2)
    when_time = m.group(3).upper().replace("  ", " ")
    ev = m.group(4).upper()
    of_cols = m.group(5)
    table = m.group(6) or m.group(7)
    when_clause = m.group(8)
    body = m.group(9).strip()
    if not body.endswith(";"):
        body += ";"

    # rewrite body statements
    def rewrite_body(b: str) -> str:
        b = rewrite_glob_in_sql(b)
        # IS NOT (null-safe) between simple terms — conservative replacement of "IS NOT" between columns
        b = re.sub(r"\s+IS\s+NOT\s+", " IS DISTINCT FROM ", b, flags=re.I)
        # undo "IS DISTINCT FROM NULL" back? "x IS NOT NULL" became "x IS DISTINCT FROM NULL" which is OK (equivalent)
        # RAISE SELECT ... WHERE
        def raise_where(mh: re.Match) -> str:
            msg = mh.group(1)
            cond = mh.group(2)
            if cond:
                return f"IF {cond} THEN RAISE EXCEPTION {msg}; END IF;"
            return f"RAISE EXCEPTION {msg};"
        b = RAISE_SELECT.sub(raise_where, b)
        def raise_case(mh: re.Match) -> str:
            return f"IF {mh.group(1)} THEN RAISE EXCEPTION {mh.group(2)}; END IF;"
        b = RAISE_CASE.sub(raise_case, b)
        return b

    body_pg = rewrite_body(body)
    # NEW/OLD are already the right names in plpgsql
    fn = f"trgfn_{tname}"
    # event time
    level = "FOR EACH ROW"
    when_sql = f" WHEN ({when_clause})" if when_clause else ""
    of_sql = f" OF {of_cols}" if of_cols and ev == "UPDATE" else ""
    # timing: INSTEAD OF only on views
    timing = when_time
    fn_sql = f"""
CREATE OR REPLACE FUNCTION {qid(fn)}() RETURNS trigger
LANGUAGE plpgsql AS $$
#variable_conflict use_column
BEGIN
  {body_pg}
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;
"""
    # PostgreSQL: FOR EACH ROW comes before WHEN
    trg_sql = (
        f"CREATE TRIGGER {qid(tname)} {timing} {ev}{of_sql} ON {qid(table)} "
        f"{level}{when_sql} EXECUTE FUNCTION {qid(fn)}();"
    )
    return fn_sql, trg_sql


def drop_schema(pcon) -> None:
    with pcon.cursor() as cur:
        cur.execute("DROP SCHEMA IF EXISTS public CASCADE")
        cur.execute("CREATE SCHEMA public")
        cur.execute("GRANT ALL ON SCHEMA public TO nafisvam")
        cur.execute("GRANT ALL ON SCHEMA public TO public")
    pcon.commit()


def install_compat(pcon) -> None:
    sql = open(COMPAT_SQL, encoding="utf-8").read()
    with pcon.cursor() as cur:
        cur.execute(sql)
    pcon.commit()


def record_sqlite_master(pcon, scon: sqlite3.Connection) -> None:
    rows = scon.execute(
        "SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL"
    ).fetchall()
    with pcon.cursor() as cur:
        cur.execute("DELETE FROM sqlite_master_sql")
        for typ, name, tbl, sql in rows:
            cur.execute(
                "INSERT INTO sqlite_master_sql(type,name,tbl_name,sql) VALUES (%s,%s,%s,%s)",
                (typ, name, tbl, sql),
            )
    pcon.commit()


def copy_table(scon, pcon, execute_values, table: str, cols: list[str], batch: int = 1000) -> int:
    select = ", ".join(qid(c) for c in cols)
    insert = f"INSERT INTO {qid(table)} ({select}) VALUES %s"
    n = 0
    cur_s = scon.execute(f"SELECT {select} FROM {qid(table)}")
    with pcon.cursor() as cur:
        while True:
            chunk = cur_s.fetchmany(batch)
            if not chunk:
                break
            # psycopg2: convert memoryview
            rows = [tuple(bytes(v) if isinstance(v, memoryview) else v for v in row) for row in chunk]
            execute_values(cur, insert, rows, page_size=batch)
            n += len(rows)
    return n


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sqlite", required=True)
    ap.add_argument("--env", required=True, help="root-only env file with PGPASSWORD (never printed)")
    ap.add_argument("--database", required=True, help="target database (nafisvam | nafisvam_masked | nafisvam_verify)")
    ap.add_argument("--skip-triggers", action="store_true")
    ap.add_argument("--keep-existing", action="store_true", help="do not drop public schema first")
    ap.add_argument("--checksum-exclude", default="", help="comma-separated tables to skip in checksum (still counted)")
    args = ap.parse_args()

    refuse_live(args.sqlite)
    if not os.path.isfile(args.sqlite):
        print("sqlite file missing", file=sys.stderr)
        return 2
    env = load_env(args.env)
    if "PGPASSWORD" not in env:
        print("env file missing PGPASSWORD", file=sys.stderr)
        return 2

    t0 = time.time()
    uri = f"file:{os.path.abspath(args.sqlite)}?mode=ro"
    scon = sqlite3.connect(uri, uri=True)
    scon.row_factory = sqlite3.Row
    try:
        ic = scon.execute("PRAGMA integrity_check").fetchone()[0]
    except Exception as e:
        print("integrity_check_error", type(e).__name__, file=sys.stderr)
        return 5
    if ic != "ok":
        print("sqlite_integrity", ic, file=sys.stderr)
        return 5
    print("sqlite_integrity ok")

    tables = list_tables(scon)
    print("sqlite_tables", len(tables))

    pcon, execute_values = pg_connect(env, args.database)
    try:
        if not args.keep_existing:
            drop_schema(pcon)
        install_compat(pcon)

        # Create tables (no FKs yet)
        creates = {}
        for table in tables:
            row = scon.execute(
                "SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (table,)
            ).fetchone()
            creates[table] = row[0] if row else None
            ddl = build_create_table(scon, table, creates[table])
            with pcon.cursor() as cur:
                cur.execute(ddl)
        pcon.commit()
        print("tables_created", len(tables))
        ensure_customer_dossier(pcon, tables)

        # Copy data before FKs and triggers are installed (no superuser needed).
        copied = 0
        for table in tables:
            cols = [c[1] for c in pragma_cols(scon, table)]
            if not cols:
                continue
            n = copy_table(scon, pcon, execute_values, table, cols)
            copied += n
            print(f"copied {table} {n}")
        pcon.commit()
        print("rows_copied", copied)

        reset_sequences(pcon, scon, tables)
        pcon.commit()
        print("sequences_reset")

        # Foreign keys
        fk_added = 0
        fk_failed = 0
        with pcon.cursor() as cur:
            for table in tables:
                # pragma: id, seq, table, from, to, on_update, on_delete, match
                fks = pragma_fks(scon, table)
                groups: dict[int, list] = {}
                for row in fks:
                    groups.setdefault(row[0], []).append(row)
                for fid, rows in groups.items():
                    src = [r[3] for r in rows]
                    dst_table = rows[0][2]
                    dst = [r[4] for r in rows]
                    on_del = rows[0][6] or "NO ACTION"
                    on_upd = rows[0][5] or "NO ACTION"
                    name = f"fk_{table}_{fid}"
                    ddl = (
                        f"ALTER TABLE {qid(table)} ADD CONSTRAINT {qid(name)} "
                        f"FOREIGN KEY ({', '.join(qid(c) for c in src)}) "
                        f"REFERENCES {qid(dst_table)} ({', '.join(qid(c) for c in dst)}) "
                        f"ON DELETE {on_del} ON UPDATE {on_upd}"
                    )
                    try:
                        cur.execute(ddl)
                        pcon.commit()
                        fk_added += 1
                    except Exception as e:
                        pcon.rollback()
                        # need a new transaction
                        fk_failed += 1
                        print(f"fk_fail {name} {type(e).__name__}")
                        # continue in a new implicit txn: reopen cursor txn
                        pcon.commit()
                        cur = pcon.cursor()
        pcon.commit()
        print("foreign_keys_added", fk_added, "failed", fk_failed)

        # Indexes (skip autoindexes that implement PK/UNIQUE already created)
        idx_ok = idx_skip = idx_fail = 0
        with pcon.cursor() as cur:
            for typ, name, tbl, sql in scon.execute(
                "SELECT type, name, tbl_name, sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL"
            ):
                if name.startswith("sqlite_autoindex_"):
                    idx_skip += 1
                    continue
                ddl = convert_index_sql(sql)
                try:
                    cur.execute(ddl)
                    pcon.commit()
                    idx_ok += 1
                except Exception as e:
                    pcon.rollback()
                    idx_fail += 1
                    print(f"index_fail {name} {type(e).__name__} {str(e).splitlines()[0][:180]}")
                    pcon.commit()
                    cur = pcon.cursor()
        pcon.commit()
        print("indexes_created", idx_ok, "skipped", idx_skip, "failed", idx_fail)

        # Views
        view_ok = view_fail = 0
        with pcon.cursor() as cur:
            views = list(scon.execute(
                "SELECT name, sql FROM sqlite_master WHERE type='view'"
            ))
            # Create independent views first (name referenced by later views).
            views.sort(key=lambda row: 0 if " customer_chat_owners" in (row[1] or "") and row[0]=="customer_chat_owners" else (0 if row[0]=="customer_chat_owners" else 1))
            for name, sql in views:
                try:
                    cur.execute(convert_view_sql(sql))
                    pcon.commit()
                    view_ok += 1
                except Exception as e:
                    pcon.rollback()
                    view_fail += 1
                    print(f"view_fail {name} {type(e).__name__} {str(e).splitlines()[0][:180]}")
                    pcon.commit()
                    cur = pcon.cursor()
        pcon.commit()
        print("views_created", view_ok, "failed", view_fail)

        # Triggers
        trg_ok = trg_fail = 0
        if not args.skip_triggers:
            with pcon.cursor() as cur:
                for name, sql in scon.execute(
                    "SELECT name, sql FROM sqlite_master WHERE type='trigger' ORDER BY name"
                ):
                    got = sqlite_trigger_to_pg(name, sql or "")
                    if not got:
                        trg_fail += 1
                        print(f"trigger_untranslated {name}")
                        continue
                    fn_sql, trg_sql = got
                    try:
                        cur.execute(fn_sql)
                        cur.execute(trg_sql)
                        pcon.commit()
                        trg_ok += 1
                    except Exception as e:
                        pcon.rollback()
                        trg_fail += 1
                        print(f"trigger_fail {name} {type(e).__name__} {str(e).splitlines()[0][:180]}")
                        pcon.commit()
                        cur = pcon.cursor()
            pcon.commit()
        print("triggers_created", trg_ok, "failed", trg_fail)

        record_sqlite_master(pcon, scon)

        # Analyze
        with pcon.cursor() as cur:
            cur.execute("ANALYZE")
        pcon.commit()

        # Verify
        exclude = {t.strip() for t in args.checksum_exclude.split(",") if t.strip()}
        mismatches = 0
        verified = 0
        for table in tables:
            cols = [c[1] for c in pragma_cols(scon, table)]
            if not cols:
                continue
            # deterministic order: PKs first then other cols
            pks = [c[1] for c in pragma_cols(scon, table) if c[5]]
            rest = [c for c in cols if c not in pks]
            order_cols = pks + rest if pks else cols
            sc, sh = checksum_sqlite(scon, table, order_cols)
            if table in exclude:
                with pcon.cursor() as cur:
                    cur.execute(f"SELECT COUNT(*) FROM {qid(table)}")
                    pc = cur.fetchone()[0]
                ok = sc == pc
                print(f"verify {table} sqlite={sc} pg={pc} checksum=skipped match={ok}")
            else:
                pc, ph = checksum_pg(pcon, table, order_cols)
                ok = sc == pc and sh == ph
                print(f"verify {table} sqlite={sc} pg={pc} checksum={'ok' if sh==ph else 'DIFF'} match={ok}")
            if not ok:
                mismatches += 1
            else:
                verified += 1
        elapsed = time.time() - t0
        print(f"verify_summary tables={len(tables)} ok={verified} mismatch={mismatches} elapsed_s={elapsed:.2f}")
        if mismatches:
            return 6
        print("MIGRATION_OK")
        return 0
    finally:
        pcon.close()
        scon.close()


if __name__ == "__main__":
    sys.exit(main())
