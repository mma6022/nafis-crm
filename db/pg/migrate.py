def qid(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def sqlite_type_to_pg(declared: str, is_pk: bool, autoincrement: bool) -> str:
    t = (declared or "").strip().upper()
    if t in ("",):
        base = "TEXT"
    elif t in ("INTEGER", "INT"):
        base = "BIGINT"
    elif t in ("REAL", "FLOAT", "DOUBLE", "DOUBLE PRECISION"):
        base = "DOUBLE PRECISION"
    elif t in ("BLOB", "BYTEA"):
        base = "BYTEA"
    else:
        # TEXT, NUMERIC typeless-ish, VARCHAR(...)
        base = "TEXT"
    if is_pk and base == "BIGINT":
        return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    return base


GLOB_RE = re.compile(r"""(?:(\w+)|"([^"]+)")\s+(NOT\s+)?GLOB\s+('(?:[^']|'')*')""", re.I)


def rewrite_bool_arith_in_sql(sql: str) -> str:
    """SQLite treats boolean as 0/1, so (a>0)+(b>0)=1 is legal. Cast in PG."""
    if not re.search(r"\)\s*[+*-]", sql):
        return sql
    def maybe(m: re.Match) -> str:
        inner = m.group(1)
        if re.search(r"[<>]|!=|<>|==|\bIS\b|\bIN\b|\bNOT\b", inner, re.I):
            return f"(({inner})::int)"
        return m.group(0)
    return re.sub(r"\(([^()]+)\)", maybe, sql)


def rewrite_glob_in_sql(sql: str) -> str:
    def repl(m: re.Match) -> str:
        col = m.group(1) or m.group(2)
        col_sql = qid(col) if m.group(2) is not None or True else col
        # keep identifier as originally quoted when possible
        raw_col = m.group(0)
        # simpler: use captured identifier
        ident = qid(m.group(2)) if m.group(2) is not None else m.group(1)
        neg = m.group(3)
        pat = m.group(4)
        expr = f"sqlite_glob({pat}, {ident})"
        return f"NOT {expr}" if neg else expr
    return GLOB_RE.sub(repl, sql)


def rewrite_sqlite_fns_in_default(dflt: str | None) -> str | None:
    if not dflt:
        return dflt
    s = dflt
    # datetime('now') / CURRENT_TIMESTAMP keep as text via our functions
    s = re.sub(r"\bCURRENT_TIMESTAMP\b", "strftime('%Y-%m-%dT%H:%M:%fZ'::text, 'now'::text)", s, flags=re.I)
    # Cast string literals so function resolution is unambiguous.
    s = re.sub(r"datetime\(\s*'now'\s*\)", "datetime('now'::text)", s, flags=re.I)
    return s


def extract_table_extras(create_sql: str | None) -> tuple[list[str], list[str]]:
    """Return (check_clauses, table_unique_or_pk_clauses) from CREATE TABLE SQL."""
    if not create_sql:
        return [], []
    # Very rough split of the top-level paren body by commas, ignoring nested parens.
    m = re.search(r"\((.*)\)\s*$", create_sql, re.S)
    if not m:
        return [], []
    body = m.group(1)
    parts: list[str] = []
    buf: list[str] = []
    depth = 0
    quote = None
    i = 0
    while i < len(body):
        ch = body[i]
        if quote:
            buf.append(ch)
            if ch == quote:
                if quote == "'" and i + 1 < len(body) and body[i + 1] == "'":
                    buf.append(body[i + 1]); i += 2; continue
                quote = None
            i += 1
            continue
        if ch in ("'", '"'):
            quote = ch
            buf.append(ch)
            i += 1
            continue
        if ch == "(":
            depth += 1
            buf.append(ch)
        elif ch == ")":
            depth -= 1
            buf.append(ch)
        elif ch == "," and depth == 0:
            parts.append("".join(buf).strip())
            buf = []
        else:
            buf.append(ch)
        i += 1
    if buf:
        parts.append("".join(buf).strip())
    checks = []
    uniques = []
    for p in parts:
        pu = p.upper()
        if re.match(r"(CONSTRAINT\s+\S+\s+)?CHECK\b", p, re.I):
            checks.append(rewrite_bool_arith_in_sql(rewrite_glob_in_sql(p)))
        elif re.match(r"(CONSTRAINT\s+\S+\s+)?(UNIQUE|PRIMARY\s+KEY)\b", p, re.I):
            uniques.append(p)
        elif re.match(r"(CONSTRAINT\s+\S+\s+)?FOREIGN\s+KEY\b", p, re.I):
            if pu.startswith("FOREIGN KEY"):
                continue
            uniques.append(p)
    return checks, uniques



def extract_all_checks(create_sql: str | None) -> list[str]:
    """Every CHECK ( ... ) in a CREATE TABLE, column-level or table-level."""
    if not create_sql:
        return []
    out: list[str] = []
    for m in re.finditer(r"\bCHECK\s*\(", create_sql, re.I):
        start = m.end() - 1
        depth, quote, j = 0, None, start
        while j < len(create_sql):
            ch = create_sql[j]
            if quote:
                if ch == quote:
                    if quote == "'" and j + 1 < len(create_sql) and create_sql[j + 1] == "'":
                        j += 2
                        continue
                    quote = None
                j += 1
                continue
            if ch in ("'", '"'):
                quote = ch
            elif ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
                if depth == 0:
                    expr = create_sql[start + 1 : j].strip()
                    clause = "CHECK (" + expr + ")"
                    out.append(rewrite_bool_arith_in_sql(rewrite_glob_in_sql(clause)))
                    break
            j += 1
    return out


def sqlite_unique_colsets(scon: sqlite3.Connection, table: str, pk_cols: list[str]) -> list[list[str]]:
    """UNIQUE constraints (PRAGMA origin='u'), including column-level UNIQUE.

    sqlite_autoindex_* for these was previously skipped at index-create time
    because we assumed CREATE TABLE already had them; column-level UNIQUE
    (e.g. loan_filing_fee_charges.application_id / idempotency_key) was missed.
    """
    out: list[list[str]] = []
    pk = tuple(pk_cols)
    for idx in pragma_indexes(scon, table):
        # seq, name, unique, origin, partial
        if len(idx) < 4 or not idx[2] or idx[3] != "u":
            continue
        cols = [r[2] for r in scon.execute(f"PRAGMA index_info({qid(idx[1])})") if r[2] is not None]
        if not cols:
            continue
        if tuple(cols) == pk:
            continue
        out.append(cols)
    return out


def unique_clause_cols(clause: str) -> tuple[str, ...]:
    m = re.search(r"\bUNIQUE\s*\((.*)\)\s*$", clause, re.I | re.S)
    if not m:
        return ()
    body, parts, buf, depth, quote = m.group(1), [], [], 0, None
    i = 0
    while i < len(body):
        ch = body[i]
        if quote:
            buf.append(ch)
            if ch == quote:
                quote = None
            i += 1
            continue
        if ch in ("'", '"'):
            quote = ch
            buf.append(ch)
        elif ch == "(":
            depth += 1
            buf.append(ch)
        elif ch == ")":
            depth -= 1
            buf.append(ch)
        elif ch == "," and depth == 0:
            parts.append("".join(buf).strip().strip('"'))
            buf = []
        else:
            buf.append(ch)
        i += 1
    if buf:
        parts.append("".join(buf).strip().strip('"'))
    return tuple(p for p in parts if p)


