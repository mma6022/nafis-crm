"""SQLite -> PostgreSQL migrator for Nafis Vam CRM.

Reads a SQLite file (prefer a backup or a MASKED copy — never the live
file in place), creates schema + data in a target Postgres database,
resets identity sequences, and verifies per-table row counts and checksums.

Does not print row values, phones, national IDs, or the database password.
Password is read from a root-only env file (--env).

Usage:
  python3 migrate.py --sqlite COPY.db --env /root/pg-migration/pg.env --database nafisvam_masked
  python3 migrate.py --sqlite COPY.db --env /root/pg-migration/pg.env --database nafisvam_verify --verify-only-after
"""
