/** Rewrite SQLite dialect used by the CRM into PostgreSQL. */

const INSERT_OR_IGNORE = /^\s*INSERT\s+OR\s+IGNORE\s+INTO/i;
const INSERT_OR_REPLACE = /^\s*INSERT\s+OR\s+REPLACE\s+INTO/i;
const BEGIN_KIND = /^\s*BEGIN\s+(IMMEDIATE|EXCLUSIVE)\b/i;

function isWordChar(ch: string | undefined): boolean {
  return !!ch && /[A-Za-z0-9_]/.test(ch);
}

function keywordAt(sql: string, i: number, word: string): boolean {
  if (isWordChar(sql[i - 1])) return false;
  if (sql.slice(i, i + word.length).toUpperCase() !== word) return false;
  return !isWordChar(sql[i + word.length]);
}

function skipSpace(sql: string, i: number): number {
  while (i < sql.length && /[\s]/.test(sql[i])) i++;
  return i;
}

/** True if `CREATE [TEMP[ORARY]] TRIGGER` starts at i. */
function isCreateTriggerAt(sql: string, i: number): boolean {
  if (!keywordAt(sql, i, "CREATE")) return false;
  let j = skipSpace(sql, i + 6);
  if (keywordAt(sql, j, "TEMPORARY") || keywordAt(sql, j, "TEMP")) {
    j = skipSpace(sql, j + (sql.slice(j, j + 9).toUpperCase() === "TEMPORARY" ? 9 : 4));
  }
  return keywordAt(sql, j, "TRIGGER");
}

export function splitStatements(sql: string): string[] {
  const parts: string[] = [];
  let buf = "";
  let str: string | null = null;
  let inTrigger = false;
  let inTriggerBody = false;
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    const next = sql[i + 1];
    if (str) {
      buf += ch;
      if (ch === str) {
        if (str === "'" && next === "'") {
          buf += sql[++i];
        } else {
          str = null;
        }
      }
      continue;
    }
    if (ch === "-" && next === "-") {
      // line comment: drop through newline, do not treat inner semicolons as separators
      i++;
      while (i + 1 < sql.length && sql[i + 1] !== "\n") i++;
      buf += "\n";
      continue;
    }
    if (ch === "/" && next === "*") {
      i += 2;
      while (i < sql.length && !(sql[i] === "*" && sql[i + 1] === "/")) i++;
      if (i < sql.length) i++; // consume /
      continue;
    }
    if (ch === "'" || ch === '"') {
      str = ch;
      buf += ch;
      continue;
    }
    if (!inTrigger && isCreateTriggerAt(sql, i)) inTrigger = true;
    if (inTrigger && !inTriggerBody && keywordAt(sql, i, "BEGIN")) {
      const after = skipSpace(sql, i + 5);
      const txn = keywordAt(sql, after, "IMMEDIATE") || keywordAt(sql, after, "EXCLUSIVE")
        || keywordAt(sql, after, "DEFERRED") || keywordAt(sql, after, "TRANSACTION");
      if (!txn) inTriggerBody = true;
    }
    if (inTriggerBody && keywordAt(sql, i, "END")) {
      // stay in body until the statement's terminating semicolon
      inTrigger = false;
      inTriggerBody = false;
      buf += ch;
      continue;
    }
    if (ch === ";" && !inTriggerBody) {
      const trimmed = buf.trim();
      if (trimmed) parts.push(trimmed);
      buf = "";
      inTrigger = false;
      inTriggerBody = false;
      continue;
    }
    buf += ch;
  }
  const trimmed = buf.trim();
  if (trimmed) parts.push(trimmed);
  return parts;
}

export function rewritePlaceholders(sql: string): string {
  let out = "";
  let n = 0;
  let str: string | null = null;
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    if (str) {
      out += ch;
      if (ch === str) {
        if (str === "'" && sql[i + 1] === "'") {
          out += sql[++i];
        } else {
          str = null;
        }
      }
      continue;
    }
    if (ch === "'" || ch === '"') {
      str = ch;
      out += ch;
      continue;
    }
    if (ch === "?") {
      n += 1;
      out += `$${n}`;
      continue;
    }
    out += ch;
  }
  return out;
}

const GLOB_RE = /(?:(\w+)|"([^"]+)")\s+(NOT\s+)?GLOB\s+('(?:[^']|'')*')/gi;

export function rewriteGlob(sql: string): string {
  return sql.replace(GLOB_RE, (_m, ident, quoted, neg, pat) => {
    const col = quoted != null ? `"${quoted}"` : ident;
    const expr = `sqlite_glob(${pat}, ${col})`;
    return neg ? `NOT ${expr}` : expr;
  });
}

export function rewriteDdl(sql: string): string {
  let s = sql;
  s = s.replace(
    /\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi,
    "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
  );
  s = s.replace(/\bINTEGER\s+PRIMARY\s+KEY\b/gi, "BIGINT PRIMARY KEY");
  // Remaining INTEGER/INT column types (not already rewritten, not in CAST/CAST AS INTEGER which PG accepts)
  s = s.replace(/\bINTEGER\b/gi, "BIGINT");
  s = s.replace(/\bINSERT\s+OR\s+IGNORE\s+INTO/gi, "INSERT INTO");
  s = s.replace(/\bINSERT\s+OR\s+REPLACE\s+INTO/gi, "INSERT INTO");
  return s;
}


/** Map a transform over SQL that is not inside '…' or "…" literals. */
function mapOutsideStrings(sql: string, fn: (chunk: string) => string): string {
  let out = "";
  let i = 0;
  while (i < sql.length) {
    const ch = sql[i];
    if (ch === "'" || ch === '"') {
      const q = ch;
      let j = i + 1;
      while (j < sql.length) {
        if (sql[j] === q) {
          if (q === "'" && sql[j + 1] === "'") { j += 2; continue; }
          j++;
          break;
        }
        j++;
      }
      out += sql.slice(i, j);
      i = j;
      continue;
    }
    let j = i + 1;
    while (j < sql.length && sql[j] !== "'" && sql[j] !== '"') j++;
    out += fn(sql.slice(i, j));
    i = j;
  }
  return out;
}

/** SQLite allows `AND 1` / `OR 0`; PostgreSQL requires a boolean. */
export function rewriteIntTruth(sql: string): string {
  return mapOutsideStrings(sql, (chunk) =>
    chunk.replace(/\b(AND|OR|WHEN)\s+([01])\b(?!\s*[=<>])/gi, (_m, kw: string, lit: string) =>
      `${kw} ${lit === "1" ? "TRUE" : "FALSE"}`,
    ),
  );
}

/** SQLite implicit rowid; PostgreSQL equivalent for ORDER BY / MIN / MAX is ctid. */
export function rewriteRowid(sql: string): string {
  return mapOutsideStrings(sql, (chunk) => chunk.replace(/\browid\b/gi, "ctid"));
}

function scanOperandEnd(s: string, start: number): number {
  let i = skipSpace(s, start);
  if (i >= s.length) return i;
  const ch = s[i];
  if (ch === "'" || ch === '"') {
    const q = ch;
    i++;
    while (i < s.length) {
      if (s[i] === q) {
        if (q === "'" && s[i + 1] === "'") { i += 2; continue; }
        i++;
        break;
      }
      i++;
    }
  } else if (ch === "(") {
    let d = 1;
    i++;
    while (i < s.length && d > 0) {
      if (s[i] === "'" || s[i] === '"') {
        const q = s[i];
        i++;
        while (i < s.length) {
          if (s[i] === q) {
            if (q === "'" && s[i + 1] === "'") { i += 2; continue; }
            i++;
            break;
          }
          i++;
        }
        continue;
      }
      if (s[i] === "(") d++;
      else if (s[i] === ")") d--;
      i++;
    }
  } else if (ch === "$" || ch === "?") {
    i++;
    while (i < s.length && /[0-9]/.test(s[i]!)) i++;
  } else if (/[A-Za-z_]/.test(ch)) {
    while (i < s.length) {
      while (i < s.length && /[A-Za-z0-9_]/.test(s[i]!)) i++;
      if (s[i] === ".") { i++; continue; }
      const k = skipSpace(s, i);
      if (s[k] === "(") {
        i = scanOperandEnd(s, k);
        continue;
      }
      break;
    }
  } else if (/[0-9.]/.test(ch)) {
    while (i < s.length && /[0-9.]/.test(s[i]!)) i++;
  }
  const after = skipSpace(s, i);
  if (s.startsWith("::", after)) {
    i = skipSpace(s, after + 2);
    while (i < s.length && /[A-Za-z0-9_]/.test(s[i]!)) i++;
  }
  return i;
}

function indexOfConcat(sql: string, from: number): number {
  let str: string | null = null;
  for (let i = from; i < sql.length; i++) {
    const ch = sql[i]!;
    if (str) {
      if (ch === str) {
        if (str === "'" && sql[i + 1] === "'") { i++; continue; }
        str = null;
      }
      continue;
    }
    if (ch === "'" || ch === '"') { str = ch; continue; }
    if (ch === "|" && sql[i + 1] === "|") return i;
  }
  return -1;
}

/** PostgreSQL `bigint || ':'` tries to cast ':' to bigint. Cast both sides of || to text. */
export function rewriteConcat(sql: string): string {
  if (!sql.includes("||")) return sql;
  let i = 0;
  let out = "";
  while (i < sql.length) {
    const j = indexOfConcat(sql, i);
    if (j < 0) {
      out += sql.slice(i);
      break;
    }
    out += sql.slice(i, j);
    if (!out.trimEnd().endsWith("::text")) out += "::text";
    out += " || ";
    const rightStart = skipSpace(sql, j + 2);
    const rightEnd = scanOperandEnd(sql, j + 2);
    const right = sql.slice(rightStart, rightEnd);
    out += sql.slice(j + 2, rightStart) + right;
    if (right && !right.trimEnd().endsWith("::text")) out += "::text";
    i = rightEnd;
  }
  return out;
}

export function rewriteStatement(sql: string): string {
  let s = sql.trim();
  if (!s) return s;
  s = s.replace(/\bmain\.sqlite_master\b/gi, "sqlite_master");
  s = s.replace(BEGIN_KIND, "BEGIN");

  // PostgreSQL has CREATE OR REPLACE VIEW, not CREATE VIEW IF NOT EXISTS.
  s = s.replace(/^\s*CREATE\s+VIEW\s+IF\s+NOT\s+EXISTS\b/i, "CREATE OR REPLACE VIEW");
  s = rewriteGlob(s);
  s = s.replace(/\bIFNULL\s*\(/gi, "COALESCE(");
  const orIgnore = INSERT_OR_IGNORE.test(s);
  const orReplace = INSERT_OR_REPLACE.test(s);
  if (orIgnore || orReplace) {
    s = s.replace(/INSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO/i, "INSERT INTO");
  }
  // DDL
  if (/^\s*CREATE\s+TABLE\b/i.test(s) || /^\s*ALTER\s+TABLE\b/i.test(s)) {
    s = rewriteDdl(s);
  }
  if (orIgnore && !/\bON\s+CONFLICT\b/i.test(s)) {
    s = appendOnConflict(s, "ON CONFLICT DO NOTHING");
  }
  if (orReplace && !/\bON\s+CONFLICT\b/i.test(s)) {
    s = appendOnConflict(s, "ON CONFLICT DO UPDATE SET id = EXCLUDED.id");
    // The above is a poor generic; if it fails at runtime we surface the error.
  }
  s = rewriteIntTruth(s);
  s = rewriteConcat(s);
  s = rewriteRowid(s);
  s = rewritePlaceholders(s);
  return s;
}

function appendOnConflict(sql: string, clause: string): string {
  const returning = sql.match(/\s+RETURNING\b[\s\S]*$/i);
  if (returning && returning.index != null) {
    return `${sql.slice(0, returning.index)} ${clause}${sql.slice(returning.index)}`;
  }
  return `${sql} ${clause}`;
}

export type PragmaKind =
  | { kind: "noop"; result?: Record<string, unknown>[] }
  | { kind: "table_info"; table: string }
  | { kind: "foreign_key_list"; table: string }
  | { kind: "foreign_key_check" }
  | { kind: "index_list"; table: string }
  | { kind: "index_info"; index: string }
  | { kind: "integrity_check" }
  | { kind: "journal_mode" }
  | null;

export function classifyPragma(sql: string): PragmaKind {
  const s = sql.trim();
  if (!/^PRAGMA\b/i.test(s)) return null;
  const body = s.replace(/^PRAGMA\s+/i, "").replace(/;+\s*$/, "").trim();
  const tableInfo = body.match(/^table_info\s*\(\s*["']?([A-Za-z0-9_]+)["']?\s*\)/i);
  if (tableInfo) return { kind: "table_info", table: tableInfo[1] };
  const fkList = body.match(/^foreign_key_list\s*\(\s*["']?([A-Za-z0-9_]+)["']?\s*\)/i);
  if (fkList) return { kind: "foreign_key_list", table: fkList[1] };
  const idxList = body.match(/^index_list\s*\(\s*["']?([A-Za-z0-9_]+)["']?\s*\)/i);
  if (idxList) return { kind: "index_list", table: idxList[1] };
  const idxInfo = body.match(/^index_info\s*\(\s*["']?([A-Za-z0-9_]+)["']?\s*\)/i);
  if (idxInfo) return { kind: "index_info", index: idxInfo[1] };
  if (/^foreign_key_check\b/i.test(body)) return { kind: "foreign_key_check" };
  if (/^integrity_check\b/i.test(body)) return { kind: "integrity_check" };
  if (/^journal_mode\b/i.test(body)) return { kind: "journal_mode" };
  // busy_timeout, foreign_keys, synchronous, wal_checkpoint, etc.
  return { kind: "noop", result: [{ [body.split(/[\s=]/)[0]]: "ok" }] };
}

export const PRAGMA_SQL = {
  table_info: (table: string) => `
    SELECT
      a.attnum - 1 AS cid,
      a.attname AS name,
      pg_catalog.format_type(a.atttypid, a.atttypmod) AS type,
      CASE WHEN a.attnotnull THEN 1 ELSE 0 END AS notnull,
      pg_get_expr(d.adbin, d.adrelid) AS dflt_value,
      COALESCE((
        SELECT i.n
        FROM (
          SELECT k.attname AS col, row_number() OVER (ORDER BY k.attnum) AS n
          FROM pg_index x
          JOIN pg_attribute k ON k.attrelid = x.indrelid AND k.attnum = ANY(x.indkey)
          WHERE x.indrelid = a.attrelid AND x.indisprimary
        ) i WHERE i.col = a.attname
      ), 0) AS pk
    FROM pg_attribute a
    JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE n.nspname = current_schema()
      AND c.relname = $1
      AND a.attnum > 0
      AND NOT a.attisdropped
    ORDER BY a.attnum
  `,
  foreign_key_list: `
    SELECT
      0 AS id,
      0 AS seq,
      ccu.table_name AS table,
      kcu.column_name AS "from",
      ccu.column_name AS "to",
      rc.update_rule AS on_update,
      rc.delete_rule AS on_delete,
      'NONE' AS match
    FROM information_schema.table_constraints tc
    JOIN information_schema.key_column_usage kcu
      ON tc.constraint_name = kcu.constraint_name AND tc.table_schema = kcu.table_schema
    JOIN information_schema.constraint_column_usage ccu
      ON ccu.constraint_name = tc.constraint_name AND ccu.table_schema = tc.table_schema
    JOIN information_schema.referential_constraints rc
      ON rc.constraint_name = tc.constraint_name AND rc.constraint_schema = tc.table_schema
    WHERE tc.constraint_type = 'FOREIGN KEY'
      AND tc.table_schema = current_schema()
      AND tc.table_name = $1
  `,
  index_list: `
    SELECT
      row_number() OVER (ORDER BY i.relname) - 1 AS seq,
      i.relname AS name,
      CASE WHEN ix.indisunique THEN 1 ELSE 0 END AS unique,
      'c' AS origin,
      CASE WHEN ix.indispartial THEN 1 ELSE 0 END AS partial
    FROM pg_index ix
    JOIN pg_class t ON t.oid = ix.indrelid
    JOIN pg_class i ON i.oid = ix.indexrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
    WHERE n.nspname = current_schema() AND t.relname = $1
    ORDER BY i.relname
  `,
  index_info: `
    SELECT
      k.ord - 1 AS seqno,
      a.attnum AS cid,
      a.attname AS name
    FROM (
      SELECT unnest(ix.indkey) AS attnum, generate_subscripts(ix.indkey, 1) AS ord, ix.indrelid, ix.indexrelid
      FROM pg_index ix
      JOIN pg_class i ON i.oid = ix.indexrelid
      JOIN pg_namespace n ON n.oid = i.relnamespace
      WHERE n.nspname = current_schema() AND i.relname = $1
    ) k
    JOIN pg_attribute a ON a.attrelid = k.indrelid AND a.attnum = k.attnum
    ORDER BY k.ord
  `,
};

export function isInsert(sql: string): boolean {
  return /^\s*INSERT\b/i.test(sql);
}

export function withReturning(sql: string): string {
  if (/\bRETURNING\b/i.test(sql)) return sql;
  if (!isInsert(sql)) return sql;
  return `${sql} RETURNING *`;
}
